	/**
	 * Adds data to the cache if it doesn't already exist.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @uses WP_Object_Cache::isset_internal() Checks to see if the cache already has data.
	 * @uses WP_Object_Cache::set()             Sets the data after the checking the cache contents existence.
	 *
	 * @param int|string $key    What to call the contents in the cache.
	 * @param mixed      $data   The contents to store in the cache.
	 * @param string     $group  Optional. Where to group the cache contents. Default 'default'.
	 * @param int        $expire Optional. When to expire the cache contents. Default 0 (maximum expiration).
	 * @return bool False if cache key and group already exist, true on success
	 */
	public function add( $key, $data, $group = 'default', $expire = 0 ) {
		// Skip persistent cache operations during WordPress installation.
		if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
			( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			return true;
		}

		if ( wp_suspend_cache_addition() ) {
			return false;
		}

		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$start = microtime( true );

		$found = null;
		$this->get( $key, $group, false, $found, false );
		if ( true === $found ) {
			$this->record_qm_operation( 'add', $this->key( $key, $group ), $group, null, $start, 'already_exists' );
			return false;
		}

		$key    = $this->key( $key, $group );
		$expire = (int) $expire;

		if ( 0 === $expire ) {
			$expire = $this->default_expiration;
		}

		if ( is_object( $data ) ) {
			$data = clone $data;
		}

		$this->cache[ $group ][ $key ] = $data;

		// Stats.
		$this->group_ops[ $group ][] = 'Add ' . $group . '/' . $key . ' (' . $expire . 's)';

		$result = $this->save( $key, $data, $group, $expire );
		$this->record_qm_operation( 'add', $key, $group, $data, $start, $result ? 'stored' : 'failed' );

		return $result;
	}

