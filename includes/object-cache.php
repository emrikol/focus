	/**
	 * Retrieves the cache contents, if it exists.
	 *
	 * The contents will be first attempted to be retrieved by searching by the
	 * key in the cache group. If the cache is hit (success) then the contents
	 * are returned.
	 *
	 * On failure, the number of cache misses will be incremented.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key What the contents in the cache are called.
	 * @param string     $group Where the cache contents are grouped.
	 * @param bool       $force Whether to force a refetch rather than relying on the local cache (default is false).
	 * @param bool       $found Optional. Whether the key was found in the cache. Disambiguates a return of false, a storable value. Passed by reference. Default null.
	 * @param bool       $stat  Optional. Whether or not to record stats.  Default true.
	 * @return bool|mixed False on failure to retrieve contents or the cache contents on success
	 */
	public function get( int|string $key, string $group = 'default', bool $force = false, ?bool &$found = null, bool $stat = true ): mixed {
		// Skip persistent cache operations during WordPress installation.
		if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
			( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			$found = false;
			return false;
		}

		if ( ! $this->is_valid_key( $key ) ) {
			$found = false;
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$key   = $this->key( $key, $group );

		// Memory cache exists, please grab.
		if ( $this->isset_internal( $key, $group ) && ! $force ) {
			// Check if the cached file has expired.
			if ( $this->focus_file_exists( $key, $group ) && $this->get_expiration( $key, $group ) < 0 ) {
				// File has expired, remove from memory cache and proceed to load fresh data.
				unset( $this->cache[ $group ][ $key ] );
			} else {
				// Stats.
				if ( $stat ) {
					$this->group_ops[ $group ][] = 'Hit (Mem): ' . $key;
					++$this->cache_hits;
				}

				$found = true;
				return $this->cache[ $group ][ $key ];
			}
		}

		// FOCUS Cache file exists, please grab.
		if ( $this->focus_file_exists( $key, $group ) ) {
			// If the object has expired, remove it from the cache and return false to force a refresh.
			if ( $this->get_expiration( $key, $group ) < 0 ) {
				$this->delete( $key, $group );

				// Stats.
				if ( $stat ) {
					$this->group_ops[ $group ][] = 'Miss (Expired): ' . $key;
					++$this->cache_misses;
				}

				$found = false;
				return false;
			}

			$file_contents = file_get_contents( $this->get_focus_file( $key, $group ) ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
			if ( false === $file_contents ) {
				$found = false;
				return false;
			}

			$serialized_data = substr( $file_contents, strlen( $this->cache_serial_header ), - strlen( $this->cache_serial_footer ) );
			if ( empty( $serialized_data ) ) {
				// Corrupted cache file, delete it.
				$this->delete( $key, $group );
				$found = false;
				return false;
			}

			$unserialized_data = maybe_unserialize( $serialized_data );
			if ( false === $unserialized_data && serialize( false ) !== $serialized_data ) { // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize
				// Corrupted cache file, delete it.
				$this->delete( $key, $group );
				$found = false;
				return false;
			}

			$this->cache[ $group ][ $key ] = $unserialized_data;

			// Stats.
			if ( $stat ) {
				$this->group_ops[ $group ][] = 'Hit (FOCUS): ' . $key;
				++$this->cache_hits;
			}

			if ( is_object( $this->cache[ $group ][ $key ] ) ) {
				$found = true;
				return clone $this->cache[ $group ][ $key ];
			}

			$found = true;
			return $this->cache[ $group ][ $key ];
		}

		if ( $stat ) {
			$this->group_ops[ $group ][] = 'Miss (Empty): ' . $key;
			++$this->cache_misses;
		}
		$found = false;
		return false;
	}

	/**
	 * Increments numeric cache item's value.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key    The cache key to increment.
	 * @param int        $offset Optional. The amount by which to increment the item's value. Default 1.
	 * @param string     $group  Optional. The group the key is in. Default 'default'.
	 * @return false|int False on failure, the item's new value on success.
	 */
	public function incr( int|string $key, int $offset = 1, string $group = 'default' ): int|false {
		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$key   = $this->key( $key, $group );

		// Key/Group doesn't exist, return false.
		if ( ! $this->isset_internal( $key, $group ) ) {
			return false;
		}

		// Get current expiration BEFORE modifying the value to avoid race conditions.
		$current_expiry = $this->get_expiration( $key, $group );
		if ( $current_expiry < 0 ) {
			// Value has expired, delete it and return false.
			$this->delete( $key, $group );
			return false;
		}

		// Sanitize value.
		$this->cache[ $group ][ $key ] = (int) $this->cache[ $group ][ $key ];

		// Sanitize offset.
		$offset = (int) $offset;

		// Increment value.
		$this->cache[ $group ][ $key ] += $offset;

		// Never go below 0.
		if ( $this->cache[ $group ][ $key ] < 0 ) {
			$this->cache[ $group ][ $key ] = 0;
		}

		// Save new value to the cache with preserved expiration.
		$this->set( $key, $this->cache[ $group ][ $key ], $group, $current_expiry );

		// Return new value.
		return $this->cache[ $group ][ $key ];
	}

	/**
	 * Replaces the contents in the cache, if contents already exist.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @see WP_Object_Cache::set()
	 *
	 * @param int|string $key    What to call the contents in the cache.
	 * @param mixed      $data   The contents to store in the cache.
	 * @param string     $group  Optional. Where to group the cache contents. Default 'default'.
	 * @param int        $expire Optional. When to expire the cache contents. Default 0 (no expiration).
	 * @return bool False if not exists, true if contents were replaced.
	 */
	public function replace( int|string $key, mixed $data, string $group = 'default', int $expire = 0 ): bool {
		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$key   = $this->key( $key, $group );

		// Key/Group doesn't exist, return false.
		if ( ! $this->isset_internal( $key, $group ) ) {
			return false;
		}

		return $this->set( $key, $data, $group, (int) $expire );
	}

	/**
	 * Sets the data contents into the cache.
	 *
	 * The cache contents is grouped by the $group parameter followed by the
	 * $key. This allows for duplicate ids in unique groups. Therefore, naming of
	 * the group should be used with care and should follow normal function
	 * naming guidelines outside of core WordPress usage.
	 *
	 * The $expire parameter is not used, because the cache will automatically
	 * expire for each time a page is accessed and PHP finishes. The method is
	 * more for cache plugins which use files.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key    What to call the contents in the cache.
	 * @param mixed      $data   The contents to store in the cache.
	 * @param string     $group  Optional. Where to group the cache contents. Default 'default'.
	 * @param int        $expire Not Used.
	 * @return true Always returns true.
	 */
	public function set( int|string $key, mixed $data, string $group = 'default', int $expire = 0 ): bool {
		// Skip persistent cache operations during WordPress installation.
		if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
			( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			return true;
		}

		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$key   = $this->key( $key, $group );

		if ( 0 === $expire ) {
			$expire = $this->default_expiration;
		}

		// Clone objects.
		if ( is_object( $data ) ) {
			$data = clone $data;
		}

		$this->cache[ $group ][ $key ] = $data;

		// Periodically check memory usage (every 100th set operation).
		static $set_counter = 0;
		++$set_counter;
		if ( 0 === $set_counter % 100 ) {
			$this->maybe_cleanup_memory();
		}

		// Stats.
		$this->group_ops[ $group ][] = 'Set ' . $group . '/' . $key . ' (' . $expire . 's)';

		return $this->save( $key, $data, $group, $expire );
	}

