	/**
	 * Determines whether a persistent cache entry has expired.
	 *
	 * @since 1.1.0
	 *
	 * @param int|string $key   Normalized cache key.
	 * @param string     $group Cache group.
	 * @return bool Whether the persistent entry has expired.
