	/**
	 * Builds a stable request context for the prefetch key.
	 *
	 * @since 1.1.0
	 *
	 * @return string Normalized request context.
	 */
	protected function get_prefetch_context(): string {
		$host        = isset( $_SERVER['HTTP_HOST'] ) ? (string) $_SERVER['HTTP_HOST'] : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		$request_uri = isset( $_SERVER['REQUEST_URI'] ) ? (string) $_SERVER['REQUEST_URI'] : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash

		if ( '' !== $host || '' !== $request_uri ) {
			$scheme = 'http';
			if ( ( isset( $_SERVER['HTTPS'] ) && 'off' !== strtolower( (string) $_SERVER['HTTPS'] ) ) || ( isset( $_SERVER['HTTP_X_FORWARDED_PROTO'] ) && 'https' === strtolower( (string) $_SERVER['HTTP_X_FORWARDED_PROTO'] ) ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
				$scheme = 'https';
			}

			if ( '' === $host && isset( $_SERVER['SERVER_NAME'] ) ) {
				$host = (string) $_SERVER['SERVER_NAME']; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			}

			$host          = strtolower( $host );
			$request_parts = explode( '?', $request_uri, 2 );
			$path          = $request_parts[0];
			$query         = $request_parts[1] ?? '';

			if ( '' === $path ) {
				$path = '/';
			}

			if ( '' === $query && isset( $_SERVER['QUERY_STRING'] ) ) {
				$query = (string) $_SERVER['QUERY_STRING']; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			}

			$query_args = $this->normalize_prefetch_query( $query );
			$context    = $scheme . '://' . $host . rtrim( $path, '/' );

			if ( substr( $context, - strlen( '://' . $host ) ) === '://' . $host ) {
				$context .= '/';
			}

			if ( ! empty( $query_args ) ) {
				$context .= '?' . http_build_query( $query_args, '', '&' );
			}

			return $context;
		}

		$script = isset( $_SERVER['SCRIPT_NAME'] ) ? (string) $_SERVER['SCRIPT_NAME'] : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash

		if ( $this->is_wp_cli() || 'cli' === PHP_SAPI ) {
			$argv = isset( $_SERVER['argv'] ) && is_array( $_SERVER['argv'] ) ? implode( ' ', array_map( 'strval', $_SERVER['argv'] ) ) : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			return 'cli:' . $script . ':' . $argv;
		}

		// @codeCoverageIgnoreStart
		return PHP_SAPI . ':' . $script;
		// @codeCoverageIgnoreEnd
	}

	/**
	 * Normalizes query arguments for stable URL hashing.
	 *
	 * @since 1.1.0
	 *
	 * @param string $query Query string.
	 * @return array Normalized query arguments.
	 */
	protected function normalize_prefetch_query( string $query ): array {
		if ( '' === $query ) {
			return array();
		}

		$query_args = array();
		parse_str( $query, $query_args );
		$this->ksort_recursive( $query_args );

		return $query_args;
	}

	/**
	 * Sorts an array recursively by key.
	 *
	 * @since 1.1.0
	 *
	 * @param array $value Array to sort.
	 * @return void
	 */
	protected function ksort_recursive( array &$value ): void {
		ksort( $value );

		foreach ( $value as &$item ) {
			if ( is_array( $item ) ) {
				$this->ksort_recursive( $item );
			}
		}
	}

	/**
	 * Loads the saved prefetch manifest and hydrates cached groups with get_multiple().
	 *
	 * @since 1.1.0
	 *
	 * @return void
	 */
	public function load_prefetch_manifest(): void {
		if ( ! $this->is_prefetch_enabled() ) {
			return;
		}

		$prefetch_key = $this->get_prefetch_key();
		if ( false === $prefetch_key ) {
			return;
		}
		$this->record_prefetch_manifest_lookup( $prefetch_key );

		$found    = null;
		$manifest = $this->get( $prefetch_key, $this->prefetch_group, false, $found, false );
		if ( true !== $found || ! is_array( $manifest ) || empty( $manifest['groups'] ) || ! is_array( $manifest['groups'] ) ) {
			return;
		}

		$started = $this->begin_prefetch_manifest_load( $prefetch_key, $manifest );

		try {
			foreach ( $manifest['groups'] as $group => $keys ) {
				if ( ! is_string( $group ) || $group === $this->prefetch_group || ! is_array( $keys ) || empty( $keys ) ) {
					continue;
				}

				$keys = $this->sanitize_prefetch_keys( $keys );
				if ( empty( $keys ) ) {
					continue;
				}

				$this->record_prefetch_requested_keys( $group, $keys );
				$this->record_prefetch_load_operation();
				$this->get_multiple( $keys, $group );

				foreach ( $keys as $key ) {
					$cache_key = $this->key( $key, $group );
					if ( $this->isset_internal( $cache_key, $group ) ) {
						$this->record_prefetch_loaded_key( $group, $cache_key );
					}
				}
			}
		} finally {
			$this->finish_prefetch_manifest_load( $started );
		}
	}

	/**
	 * Saves the current runtime cache key manifest for the current URL/context.
	 *
	 * @since 1.1.0
	 *
	 * @return void
	 */
	public function save_prefetch_manifest(): void {
		if ( ! $this->is_prefetch_enabled() || empty( $this->cache ) ) {
			return;
		}

		$prefetch_key = $this->get_prefetch_key();
		if ( false === $prefetch_key ) {
			return;
		}

		$started = microtime( true );
		$groups  = $this->build_prefetch_groups();
		if ( empty( $groups ) ) {
			return;
		}

		$manifest = array(
			'version' => 1,
			'created' => time(),
			'groups'  => $groups,
		);

		$result = $this->set( $prefetch_key, $manifest, $this->prefetch_group, WP_FOCUS_PREFETCH_TTL );
		$this->record_prefetch_manifest_save( $groups, $started, $result );
	}

	/**
	 * Backward-compatible wrapper for the old preload method name.
	 *
	 * @since 1.1.0
	 *
	 * @return void
	 */
	public function save_preload_cache(): void {
		$this->save_prefetch_manifest();
	}

	/**
	 * Builds a grouped list of runtime cache keys suitable for a prefetch manifest.
	 *
	 * @since 1.1.0
	 *
	 * @return array Grouped prefetch keys.
	 */
	protected function build_prefetch_groups(): array {
		$groups = array();

		foreach ( $this->cache as $group => $items ) {
			if ( ! is_string( $group ) || $group === $this->prefetch_group || ! is_array( $items ) || ! $this->should_persist( $group ) ) {
				continue;
			}

			$keys = $this->sanitize_prefetch_keys( array_keys( $items ) );
			if ( empty( $keys ) ) {
				continue;
			}

			$groups[ $group ] = $keys;
		}

		return $groups;
	}

	/**
	 * Sanitizes and de-duplicates manifest keys without triggering doing-it-wrong notices.
	 *
	 * @since 1.1.0
	 *
	 * @param array $keys Cache keys.
	 * @return array Sanitized keys.
	 */
	protected function sanitize_prefetch_keys( array $keys ): array {
		$sanitized = array();

		foreach ( $keys as $key ) {
			if ( is_int( $key ) || ( is_string( $key ) && '' !== trim( $key ) ) ) {
				$sanitized[ (string) $key ] = $key;
			}
		}

		return array_values( $sanitized );
	}

	/**
	 * Serves as a utility function to create cache group directories.
	 *
	 * @param string $group Cache group for directory creation.
	 *
	 * @return string The cache group directory.
	 */
	protected function make_group_dir( string $group = 'default' ): string {
		$cache_dir = $this->cache_dir;
		$make_dir  = '';

		foreach ( explode( '/', $group ) as $subdir ) {
			$make_dir .= $subdir . '/';
			$this->mkdir( $cache_dir . $make_dir );
		}

		return $cache_dir . $group . '/';
	}

	/**
	 * Serves as a utility function to create directories.
	 *
	 * @param string $dir Directory to create.
	 *
	 * @return bool True on success, false on failure.
	 */
	protected function mkdir( string $dir ): bool {
		// Give the new dirs the same perms as wp-content.
		$stat = stat( ABSPATH . 'wp-content' );
		// @codeCoverageIgnoreStart
		if ( false === $stat ) {
			// Fallback permissions for test environment or when wp-content doesn't exist.
			$dir_perms  = 0755; // rwxr-xr-x.
			$file_perms = 0644; // rw-r--r--.
		} else {
			// @codeCoverageIgnoreEnd
			$dir_perms  = $stat['mode'] & 0007777; // Get the permission bits.
			$file_perms = $dir_perms & 0000666; // Remove execute bits for files.
		}

		// Make the base cache dir.
		if ( ! file_exists( $dir ) ) {
			// @codeCoverageIgnoreStart
			if ( ! mkdir( $dir ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_mkdir
				return false;
			}
			// @codeCoverageIgnoreEnd
			chmod( $dir, $dir_perms ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_chmod
		}

		if ( ! file_exists( $dir . 'index.php' ) ) {
			touch( $dir . 'index.php' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_touch
			chmod( $dir . 'index.php', $file_perms ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_chmod
		}

		return is_dir( $dir ) && is_writable( $dir ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_is_writable
	}

	/**
	 * Serves as a utility function to delete directories.
	 *
	 * @param string $dir Directory to delete.
	 *
	 * @return bool True on success, false on failure.
	 */
	protected function rm_cache_dir( string $dir ): bool {
		$dir_object = @opendir( $dir ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged

		if ( false === $dir_object ) {
			return false;
		}

		$file_object = readdir( $dir_object );
		while ( false !== $file_object ) {
			if ( '.' === $file_object || '..' === $file_object ) {
				$file_object = readdir( $dir_object );
				continue;
			}

			$dir_path = $dir . DIRECTORY_SEPARATOR . $file_object;

			if ( is_dir( $dir_path ) ) {
				$this->rm_cache_dir( $dir_path );
			} else {
				unlink( $dir_path ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			}
			$file_object = readdir( $dir_object );
		}

		closedir( $dir_object );
		rmdir( $dir ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_rmdir

		return true;
	}

