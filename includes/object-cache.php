/**
 * From WordPress Core: Adds data to the cache, if the cache key doesn't already exist.
 *
 * @param int|string $key    The cache key to use for retrieval later.
 * @param mixed      $data   The data to add to the cache.
 * @param string     $group  Optional. The group to add the cache to. Enables the same key
 *                           to be used across groups. Default empty.
 * @param int        $expire Optional. When the cache data should expire, in seconds.
 *                           Default 0 (no expiration).
 * @return bool False if cache key and group already exist, true on success.
 */
function wp_cache_add( int|string $key, mixed $data, string $group = 'default', int $expire = 0 ): bool {
	global $wp_object_cache;

	// Skip persistent cache operations during WordPress installation.
	if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
