/**
 * Creates the configured FOCUS object-cache implementation.
 *
 * @return WP_Object_Cache The configured object cache instance.
 */
function focus_cache_create_object_cache(): WP_Object_Cache {
	$backend = strtolower( trim( (string) WP_FOCUS_BACKEND ) );

	if ( in_array( $backend, array( 'database', 'db' ), true ) && class_exists( 'FOCUS_Database_Object_Cache' ) ) {
		// @codeCoverageIgnoreStart
		return new FOCUS_Database_Object_Cache();
		// @codeCoverageIgnoreEnd
	}

	if ( class_exists( 'FOCUS_File_Object_Cache' ) ) {
		return new FOCUS_File_Object_Cache();
	}

	// @codeCoverageIgnoreStart
	return new WP_Object_Cache();
	// @codeCoverageIgnoreEnd
}

