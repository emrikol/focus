	/**
	 * Serves as a utility function to determine the cache expiration.
	 *
	 * @since 0.1.0
	 * @access protected
	 *
	 * @param int|string $key   Cache key to check.
	 * @param string     $group Cache group for the key check.
	 * @return int Seconds until the cache expires.
	 */
	protected function get_expiration( int|string $key, string $group ): int {
		$cache_key    = $group . ':' . $key;
		$current_time = time();

		// Check if we have a cached expiration result from this request.
		if ( isset( $this->expiration_cache[ $cache_key ] ) ) {
			$cached_data = $this->expiration_cache[ $cache_key ];
			// Use cached result if it's from the same second (transaction-level caching).
			if ( $current_time === $cached_data['calculated_at'] ) {
				return ( $cached_data['mtime'] - $current_time );
			}
		}

		if ( $this->focus_file_exists( $key, $group ) ) {
			$file_path = $this->get_focus_file( $key, $group );
			$mtime     = filemtime( $file_path );

			// Cache the result for this transaction (same-second requests).
			$this->expiration_cache[ $cache_key ] = array(
				'mtime'         => $mtime,
				'calculated_at' => $current_time,
			);

			return ( $mtime - $current_time );
		}

		return 0;
	}

	/**
	 * Serves as a utility function to determine the cache file.
	 *
	 * @since 0.1.0
	 * @access protected
	 *
	 * @param int|string $key   Cache key to check.
	 * @param string     $group Cache group for the key check.
	 * @return string The cache file.
	 */
	protected function get_focus_file( int|string $key, string $group ): string {
		$cache_key = $group . ':' . $key;

		// Check if we already calculated this path.
		if ( isset( $this->file_path_cache[ $cache_key ] ) ) {
			return $this->file_path_cache[ $cache_key ];
		}

		// Some characters might cause problems with the file system.
		$protected_chars = array(
			'/'  => rawurlencode( '/' ),
			'\\' => rawurlencode( '\\' ),
			'?'  => rawurlencode( '?' ),
			'*'  => rawurlencode( '*' ),
			'|'  => rawurlencode( '|' ),
			'"'  => rawurlencode( '"' ),
			'\'' => rawurlencode( '\'' ),
			'<'  => rawurlencode( '<' ),
			'>'  => rawurlencode( '>' ),
			':'  => rawurlencode( ':' ),
		);

		$safe_key  = str_replace( array_keys( $protected_chars ), $protected_chars, $key );
		$file_path = $this->cache_dir . $group . '/' . $safe_key . '.php';

		// Cache the result for future use.
		$this->file_path_cache[ $cache_key ] = $file_path;

		// Cleanup file path cache if it gets too large.
		if ( count( $this->file_path_cache ) > $this->max_file_path_cache_items ) {
			$this->file_path_cache = array_slice( $this->file_path_cache, -$this->file_path_cache_cleanup_size, null, true );
		}

		return $file_path;
	}

	/**
	 * Normalizes key
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key   Cache key to check.
	 * @param string     $group Cache group for the key check.
	 * @return string Normalized copy of key.
	 */
	public function key( int|string $key, string $group ): string {
		$group = $this->sanitize_cache_group( $group );

		$prefix = $this->key_salt;

		if ( ! empty( $this->global_groups[ $group ] ) ) {
			$prefix .= $this->global_prefix;
		} else {
			$prefix .= $this->blog_prefix;
		}

		if ( empty( $prefix ) ) {
			$prefix = 'WP';
		}

		// Remove whitespace.
		$prefix = preg_replace( '/\s+/', '', $prefix );
		$key    = preg_replace( '/\s+/', '', (string) $key );

		$normalized_key = $prefix . ':' . $key;

		// Remove dulicate prefixes.  Where are these coming from?!
		$normalized_key = preg_replace( '/^' . $prefix . ':' . $prefix . ':/', $prefix . ':', $normalized_key );

		return $normalized_key;
	}

	/**
	 * Salts cache key prefix
	 *
	 * @since 0.1.0
	 * @access protected
	 *
	 * @param string $key_salt Salt to use.
	 */
	protected function salt_keys( string $key_salt ): void {
		if ( strlen( $key_salt ) ) {
			$this->key_salt = $key_salt . ':';
		} else {
			$this->key_salt = '';
		}
	}

	/**
	 * Generates a normalized preload cache key based on domain, URL and query parameters.
	 * Used to uniquely identify cache preload files for specific pages across multiple domains.
	 *
	 * @since 1.1.0
	 * @access protected
	 *
	 * @return string|false Normalized preload cache key including domain and blog context, or false if preload is disabled.
	 */
	public function get_preload_key(): string|false {
		// Skip if preload is not enabled.
		if ( ! WP_FOCUS_CACHE_PRELOAD && ! ( isset( $this->test_preload_enabled ) && $this->test_preload_enabled ) ) {
			return false;
		}

		global $blog_id;

		// Skip preload for non-web contexts.
		if ( $this->is_wp_cli() ) {
			return false; // Disable preload for WP-CLI.
		}
		if ( $this->is_doing_cron() ) {
			return false; // Disable preload for cron jobs.
		}
		if ( $this->is_xmlrpc_request() ) {
			return false; // Disable preload for XML-RPC requests.
		}

		// Skip preload for non-GET requests.
		$request_method = isset( $_SERVER['REQUEST_METHOD'] ) ? $_SERVER['REQUEST_METHOD'] : 'GET'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
		if ( 'GET' !== $request_method ) {
			return false; // Only preload GET requests.
		}

		// Get domain for multi-domain WordPress sites.
		$domain      = isset( $_SERVER['HTTP_HOST'] ) ? $_SERVER['HTTP_HOST'] : 'localhost'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
		$domain_hash = md5( $domain );

		// Get current URL and normalize it.
		$url = '';
		if ( isset( $_SERVER['REQUEST_URI'] ) ) {
			$url = $_SERVER['REQUEST_URI']; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
		}

		// Remove trailing slash for consistency.
		$url = rtrim( $url, '/' );

		// Handle query parameters - sort them for consistency.
		$query_params = array();
		if ( isset( $_SERVER['QUERY_STRING'] ) && ! empty( $_SERVER['QUERY_STRING'] ) ) {
			parse_str( $_SERVER['QUERY_STRING'], $query_params ); // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
			ksort( $query_params );
		}

		// Build normalized URL with sorted query string.
		$normalized_url = $url;
		if ( ! empty( $query_params ) ) {
			$normalized_url .= '?' . http_build_query( $query_params );
		}

		// Create hash for the URL to avoid filesystem issues.
		$url_hash = md5( $normalized_url );

		// Include domain and blog ID for multisite and multi-domain support.
		$blog_id     = isset( $blog_id ) ? $blog_id : 1; // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited
		$preload_key = $domain_hash . '_' . $url_hash . '_' . $blog_id;

		return $preload_key;
	}

	/**
	 * Loads cache preload data from disk if available and not expired.
	 * Implements two-level expiration validation for optimal performance.
	 *
	 * @since 1.1.0
	 * @access protected
	 */
	protected function load_preload_cache(): void {
		// Skip during WordPress installation.
		if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
			( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
			return;
		}

		$preload_key = $this->get_preload_key();
		// Skip if preload is disabled for this context.
		if ( false === $preload_key ) {
			return;
		}

		$preload_file = $this->preload_dir . $preload_key . '.php';

		// First level: Check if preload file exists and is not expired.
		if ( ! file_exists( $preload_file ) ) {
			return;
		}

		$preload_file_time = filemtime( $preload_file );
		if ( ! $preload_file_time || ( $preload_file_time + WP_FOCUS_PRELOAD_TTL ) <= time() ) {
			// Preload file is expired, clean it up and skip.
			unlink( $preload_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return;
		}

		// Load and deserialize preload data.
		$preload_data = $this->load_preload_file( $preload_file );
		if ( ! $preload_data || ! isset( $preload_data['cache_data'] ) || ! isset( $preload_data['file_times'] ) ) {
			// Corrupted preload file, clean it up.
			unlink( $preload_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return;
		}

		$current_time = time();

		// Second level: Validate individual cache items and restore non-expired ones.
		foreach ( $preload_data['cache_data'] as $group => $items ) {
			// Skip non-persistent groups. (they shouldn't be in preload anyway).
			if ( ! empty( $this->non_persistent_groups[ $group ] ) ) {
				continue;
			}

			foreach ( $items as $key => $value ) {
				// Check if we have file time data for this item.
				if ( ! isset( $preload_data['file_times'][ $group ][ $key ] ) ) {
					continue;
				}

				$item_filemtime = $preload_data['file_times'][ $group ][ $key ];

				// Check if item is expired using FOCUS cache logic (filemtime < current_time).
				if ( $item_filemtime < $current_time ) {
					continue; // Skip expired item.
				}

				// Item is valid, restore it to cache.
				if ( ! isset( $this->cache[ $group ] ) ) {
					$this->cache[ $group ] = array();
				}
				$this->cache[ $group ][ $key ] = $value;
			}
		}
	}

	/**
	 * Loads and deserializes a preload file from disk.
	 *
	 * @since 1.1.0
	 * @access protected
	 *
	 * @param string $preload_file Path to the preload file.
	 * @return array|false Preload data array or false on failure.
	 */
	protected function load_preload_file( string $preload_file ): array|false {
		$contents = file_get_contents( $preload_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		if ( false === $contents ) {
			return false;
		}

		// Extract serialized data from the PHP file format.
		$data = substr( $contents, strlen( $this->cache_serial_header ), - strlen( $this->cache_serial_footer ) );
		if ( empty( $data ) ) {
			return false;
		}

		// Unserialize the data.
		$value = unserialize( $data ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_unserialize
		if ( false === $value && serialize( false ) !== $data ) { // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize
			return false;
		}

		return $value;
	}

	/**
	 * Saves the current cache state to a preload file for future requests.
	 * Captures expiration metadata by checking individual cache file timestamps.
	 *
	 * @return void
	 */
	public function save_preload_cache(): void {
		// Skip if preload is not enabled.
		if ( ! WP_FOCUS_CACHE_PRELOAD && ! ( isset( $this->test_preload_enabled ) && $this->test_preload_enabled ) ) {
			return;
		}

		// Skip during WordPress installation or if cache is empty.
		if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
			( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) || // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.MissingUnslash, WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
			empty( $this->cache ) ) {
			return;
		}

		$preload_key = $this->get_preload_key();
		// Skip if preload is disabled for this context.
		if ( false === $preload_key ) {
			return;
		}

		$preload_file = $this->preload_dir . $preload_key . '.php';

		// If the preload file is less than 5 minutes old, skip saving.
		if ( file_exists( $preload_file ) && ( filemtime( $preload_file ) + WP_FOCUS_PRELOAD_TTL ) > time() ) {
			return; // Preload file is still fresh, no need to save again.
		}

		// Build cache data and file time metadata.
		$cache_data_to_save = array();
		$file_times         = array();

		foreach ( $this->cache as $group => $items ) {
			// Skip non-persistent groups.
			if ( ! empty( $this->non_persistent_groups[ $group ] ) ) {
				continue;
			}

			foreach ( $items as $key => $value ) {
				// Get the cache file for this item to check its file time.
				$cache_file = $this->get_focus_file( $key, $group );

				if ( file_exists( $cache_file ) ) {
					$cache_file_time = filemtime( $cache_file );

					// Only include items with valid file times.
					if ( false !== $cache_file_time ) {
						// Store cache data and file time.
						if ( ! isset( $cache_data_to_save[ $group ] ) ) {
							$cache_data_to_save[ $group ] = array();
							$file_times[ $group ]         = array();
						}

						$cache_data_to_save[ $group ][ $key ] = $value;
						$file_times[ $group ][ $key ]         = $cache_file_time;
					}
				}
			}
		}

		// Don't create empty preload files.
		if ( empty( $cache_data_to_save ) ) {
			return;
		}

		// Build simplified preload data structure.
		$preload_data = array(
			'cache_data' => $cache_data_to_save,
			'file_times' => $file_times,
		);

		// Save preload file using the same format as regular cache files.
		$this->save_preload_file( $preload_file, $preload_data );
	}

	/**
	 * Saves preload data to disk using the same format as regular cache files.
	 *
	 * @since 1.1.0
	 * @access protected
	 *
	 * @param string $preload_file Path to save the preload file.
	 * @param array  $preload_data The preload data to save.
	 * @return bool True on success, false on failure.
	 */
	protected function save_preload_file( string $preload_file, array $preload_data ): bool {
		// Ensure preload directory exists.
		if ( ! is_dir( $this->preload_dir ) ) {
			$this->mkdir( $this->preload_dir );
		}

		// Create temporary file.
		$temp_file = tempnam( $this->preload_dir, 'preload_tmp' );
		if ( false === $temp_file ) {
			return false;
		}

		// Serialize and add header/footer.
		$serial = $this->cache_serial_header . serialize( $preload_data ) . $this->cache_serial_footer; // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize

		$fd = fopen( $temp_file, 'w' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fopen
		if ( false === $fd ) {
			unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return false;
		}

		$fwrite = fwrite( $fd, $serial ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite
		fclose( $fd ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose

		if ( false === $fwrite ) {
			unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return false;
		}

		// Atomic move to final location.
		if ( ! rename( $temp_file, $preload_file ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename
			unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return false;
		}

		return true;
	}

	/**
	 * Serves as a utility function to create cache group directories.
	 *
	 * @param string $group Cache group for directory creation.
	 *
	 * @return string The cache group directory.
	 */
	protected function make_group_dir( string $group = 'default' ): string {
		$cache_dir = $this->cache_dir;
		$make_dir  = '';

		foreach ( explode( '/', $group ) as $subdir ) {
			$make_dir .= $subdir . '/';
			$this->mkdir( $cache_dir . $make_dir );
		}

		return $cache_dir . $group . '/';
	}

	/**
	 * Serves as a utility function to create directories.
	 *
	 * @param string $dir Directory to create.
	 *
	 * @return bool True on success, false on failure.
	 */
	protected function mkdir( string $dir ): bool {
		// Give the new dirs the same perms as wp-content.
		$stat = stat( ABSPATH . 'wp-content' );
		if ( false === $stat ) {
			// Fallback permissions for test environment or when wp-content doesn't exist.
			$dir_perms  = 0755; // rwxr-xr-x.
			$file_perms = 0644; // rw-r--r--.
		} else {
			$dir_perms  = $stat['mode'] & 0007777; // Get the permission bits.
			$file_perms = $dir_perms & 0000666; // Remove execute bits for files.
		}

		// Make the base cache dir.
		if ( ! file_exists( $dir ) ) {
			if ( ! mkdir( $dir ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_mkdir
				return false;
			}
			chmod( $dir, $dir_perms ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_chmod
		}

		if ( ! file_exists( $dir . 'index.php' ) ) {
			touch( $dir . 'index.php' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_touch
			chmod( $dir . 'index.php', $file_perms ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_chmod
		}

		return is_dir( $dir ) && is_writable( $dir ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_is_writable
	}

	/**
	 * Serves as a utility function to delete directories.
	 *
	 * @param string $dir Directory to delete.
	 *
	 * @return bool True on success, false on failure.
	 */
	protected function rm_cache_dir( string $dir ): bool {
		$dir_object = @opendir( $dir ); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged

		if ( false === $dir_object ) {
			return false;
		}

		$file_object = readdir( $dir_object );
		while ( false !== $file_object ) {
			if ( '.' === $file_object || '..' === $file_object ) {
				$file_object = readdir( $dir_object );
				continue;
			}

			$dir_path = $dir . DIRECTORY_SEPARATOR . $file_object;

			if ( is_dir( $dir_path ) ) {
				$this->rm_cache_dir( $dir_path );
			} else {
				unlink( $dir_path ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			}
			$file_object = readdir( $dir_object );
		}

		closedir( $dir_object );
		rmdir( $dir ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_rmdir

		return true;
	}

	/**
	 * Serves as a utility function to create multisite cache group names.
	 *
	 * @param string $group Cache group to sanitize.
	 *
	 * @return string Sanitized cache group.
	 */
	public function sanitize_cache_group( string $group ): string {
		if ( empty( $group ) ) {
			$group = 'default';
		}
		return $group;
	}

	/**
	 * Determines whether a key is valid.
	 *
	 * @param int|string $key Cache key to validate.
	 *
	 * @return bool Whether the key is valid.
	 */
	protected function is_valid_key( int|string $key ): bool {
		if ( is_int( $key ) ) {
			return true;
		}

		if ( is_string( $key ) && '' !== trim( $key ) ) {
			return true;
		}

		$type = gettype( $key );

		if ( ! function_exists( '__' ) ) {
			wp_load_translations_early();
		}

		/* translators: %s: The type of the given cache key. */
		$message = sprintf( __( 'Cache key must be integer or non-empty string, %s given.', 'focus-cache' ), $type );
		_doing_it_wrong( esc_html( sprintf( '%s::%s', __CLASS__, debug_backtrace( DEBUG_BACKTRACE_IGNORE_ARGS, 2 )[1]['function'] ) ), esc_html( $message ), '6.1.0' ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_debug_backtrace

		return false;
	}


	/**
	 * Serves as a utility function to save the cache data to a file.
	 *
	 * @param int|string $key    What to call the contents in the cache.
	 * @param mixed      $data   The contents to store in the cache.
	 * @param string     $group  Optional. Where to group the cache contents. Default 'default'.
	 * @param int        $expire Cache expiration.
	 *
	 * @return bool True on success, false on failure.
	 */
	protected function save( int|string $key, mixed $data, string $group = 'default', int $expire = 0 ): bool {
		// Skip file operations for non-persistent groups.
		if ( ! $this->should_persist( $group ) ) {
			return true;
		}

		// Check available disk space (fail if less than 10MB available).
		$cache_dir  = $this->cache_dir;
		$free_bytes = disk_free_space( $cache_dir );
		if ( false !== $free_bytes && $free_bytes < $this->min_disk_space ) {
			// Log the issue but don't fail completely - just don't persist to disk.
			error_log( 'FOCUS Cache: Low disk space warning. Available: ' . round( $free_bytes / 1048576, 1 ) . 'MB' ); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
			return false;
		}

		if ( 0 === $expire ) {
			$expire = $this->default_expiration;
		}

		// Give the new dirs the same perms as wp-content.
		$stat = stat( ABSPATH . 'wp-content' );
		if ( false === $stat ) {
			// Fallback permissions for test environment or when wp-content doesn't exist.
			$dir_perms  = 0755; // rwxr-xr-x.
			$file_perms = 0644; // rw-r--r--.
		} else {
			$dir_perms  = $stat['mode'] & 0007777; // Get the permission bits.
			$file_perms = $dir_perms & 0000666; // Remove execute bits for files.
		}

		// Make FOCUS Cache directories and temp file.
		$this->mkdir( $cache_dir );
		$group_dir  = $this->make_group_dir( $group );
		$cache_file = $this->get_focus_file( $key, $group );
		$temp_file  = tempnam( $cache_dir, 'tmp' );
		if ( false === $temp_file ) {
			return false;
		}

		// Serialize and add Header/Footer.
		// `maybe_serialize()` causes issues with variable typing, can't use.
		$serial = $this->cache_serial_header . serialize( $data ) . $this->cache_serial_footer; // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize

		$fd = fopen( $temp_file, 'w' ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fopen
		if ( false === $fd ) {
			return false;
		}

		$fwrite = fwrite( $fd, $serial ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite
		if ( false === $fwrite ) {
			return false;
		}

		fclose( $fd ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fclose

		if ( ! rename( $temp_file, $cache_file ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename
			unlink( $temp_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return false;
		}

		$chmod = chmod( $cache_file, $file_perms ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_chmod
		if ( false === $chmod ) {
			return false;
		}

		// Set expiry.
		$touch = touch( $cache_file, time() + $expire ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_touch
		if ( false === $touch ) {
			return false;
		}

		// Invalidate expiration cache since we just wrote a new file with new expiration.
		$this->invalidate_expiration_cache( $key, $group );

		return true;
	}

	/**
	 * Ensures that a cache directory exists for the given group.
	 * This is an optimization for batch operations to avoid repeated directory creation.
	 *
	 * @param string $group The cache group.
	 *
	 * @return bool True if directory exists or was created, false on failure.
	 */
	protected function ensure_cache_dir_exists( string $group ): bool {
		$cache_dir = $this->cache_dir . DIRECTORY_SEPARATOR . $group;

		if ( is_dir( $cache_dir ) ) {
			return true;
		}

		$this->make_group_dir( $group );
		return is_dir( $cache_dir );
	}

	/**
	 * Loads a cache value directly from disk without checking memory cache.
	 * This is used for batch operations to avoid memory cache pollution.
	 *
	 * @param string $key   The cache key.
	 * @param string $group The cache group.
	 *
	 * @return mixed The cached value on success, false on failure.
	 */
	protected function load_from_disk( string $key, string $group ): mixed {
		// Check if file exists and hasn't expired.
		if ( ! $this->focus_file_exists( $key, $group ) ) {
			return false;
		}

		$cache_file = $this->get_focus_file( $key, $group );

		// Check expiration (negative value means expired).
		if ( $this->get_expiration( $key, $group ) < 0 ) {
			// File has expired, delete it.
			unlink( $cache_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
			return false;
		}

		// Load and decode the data.
		$contents = file_get_contents( $cache_file ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents
		if ( false === $contents ) {
			return false;
		}

		// Extract serialized data from the PHP file format..
		$data = substr( $contents, strlen( $this->cache_serial_header ), - strlen( $this->cache_serial_footer ) );
		if ( empty( $data ) ) {
			return false;
		}

		// Unserialize the data..
		$value = unserialize( $data ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_unserialize
		if ( false === $value && serialize( false ) !== $data ) { // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize
			return false;
		}

		return $value;
	}

	/**
	 * Invalidates cached expiration data for a specific key.
	 * Called when we write to a file to ensure expiration cache stays fresh.
	 *
	 * @param string $key   The cache key.
	 * @param string $group The cache group.
	 *
	 * @return void
	 */
	protected function invalidate_expiration_cache( string $key, string $group ): void {
		$cache_key = $group . ':' . $key;
		unset( $this->expiration_cache[ $cache_key ] );
	}

	/**
	 * Checks FOCUS-specific cache memory usage and performs cleanup if necessary.
	 * Only manages FOCUS internal caches, not WordPress core's cache.
	 *
	 * @return void
	 */
	protected function maybe_cleanup_memory(): void {
		// Only cleanup FOCUS-specific auxiliary caches.
		// WordPress core manages $this->cache memory itself.

		// Cleanup file path cache if it gets too large..
		if ( count( $this->file_path_cache ) > $this->max_file_path_cache_items ) {
			$this->file_path_cache = array_slice( $this->file_path_cache, -$this->file_path_cache_cleanup_size, null, true );
		}

		// Cleanup expiration cache if it gets too large.
		if ( count( $this->expiration_cache ) > $this->max_expiration_cache_items ) {
			$this->expiration_cache = array_slice( $this->expiration_cache, -$this->expiration_cache_cleanup_size, null, true );
		}

		// Group operations are preserved for debugging.
	}
