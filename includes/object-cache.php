/**
 * Removes all cache items in a group, if the object cache implementation supports it.
 *
 * Before calling this function, always check for group flushing support using the
 * `wp_cache_supports( 'flush_group' )` function.
 *
 * @param string $group Name of group to remove from cache.
 *
 * @return bool True if group was flushed, false otherwise.
 */
function wp_cache_flush_group( $group ) {
	global $wp_object_cache;

	// Skip persistent cache operations during WordPress installation.
	if ( ( defined( 'WP_INSTALLING' ) && WP_INSTALLING ) ||
		( isset( $_SERVER['SCRIPT_NAME'] ) && strpos( $_SERVER['SCRIPT_NAME'], 'install.php' ) !== false ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized, WordPress.Security.ValidatedSanitizedInput.MissingUnslash
		return true;
	}

	/**
	 * WordPress core expects external object caches to trigger a "doing it wrong" notice
	 * and return false unless they explicitly support group flushing through wp_cache_supports().
	 * This maintains compatibility with WordPress core tests and expectations.
	 * See: WordPress core test Tests_Cache::test_wp_cache_flush_group()
	 */
	if ( wp_using_ext_object_cache() ) {
		// @codeCoverageIgnoreStart
		if ( ! wp_cache_supports( 'flush_group' ) ) {
			_doing_it_wrong(
				__FUNCTION__,
				esc_html__( 'wp_cache_flush_group() is not supported by the current object cache backend.', 'focus-cache' ),
				'6.1.0'
			);
			return false;
		}
		// @codeCoverageIgnoreEnd
	}

	// Cache supports group flushing - proceed with the operation.
	if ( method_exists( $wp_object_cache, 'flush_group' ) ) {
		return $wp_object_cache->flush_group( $group );
	}

	// Fallback - should not reach here if wp_cache_supports is implemented correctly.
	return false;
}

/**
 * Retrieves cached data if valid and unchanged.
 *
 * @param string       $cache_key The cache key used for storage and retrieval.
 * @param string       $group     The cache group used for organizing data.
 * @param string|array $salt      The timestamp or timestamps indicating when the cache group was last updated.
 * @return mixed The cached data if valid, false if not found or outdated.
 */
function wp_cache_get_salted( $cache_key, $group, $salt ) {
	$salt  = is_array( $salt ) ? implode( ':', $salt ) : $salt;
	$cache = wp_cache_get( $cache_key, $group );

	if ( ! is_array( $cache ) ) {
		return false;
	}

	if ( ! isset( $cache['salt'] ) || ! isset( $cache['data'] ) || $salt !== $cache['salt'] ) {
		return false;
	}

	return $cache['data'];
}

/**
 * Stores salted data in the cache.
 *
 * @param string       $cache_key The cache key under which to store the data.
 * @param mixed        $data      The data to be cached.
 * @param string       $group     The cache group.
 * @param string|array $salt      The timestamp or timestamps indicating when the cache group was last updated.
 * @param int          $expire    Optional. When to expire the cache contents, in seconds. Default 0.
 * @return bool True on success, false on failure.
 */
function wp_cache_set_salted( $cache_key, $data, $group, $salt, $expire = 0 ) {
	$salt = is_array( $salt ) ? implode( ':', $salt ) : $salt;

	return wp_cache_set(
		$cache_key,
		array(
			'data' => $data,
			'salt' => $salt,
		),
		$group,
		$expire
	);
}

/**
 * Retrieves multiple cached values, only returning data with the expected salt.
 *
 * @param string[]     $cache_keys Array of cache keys to retrieve.
 * @param string       $group      The cache group.
 * @param string|array $salt       The timestamp or timestamps indicating when the cache group was last updated.
 * @return array Array of cache values keyed by cache key. Stale or missing values are false.
 */
function wp_cache_get_multiple_salted( $cache_keys, $group, $salt ) {
	$salt  = is_array( $salt ) ? implode( ':', $salt ) : $salt;
	$cache = wp_cache_get_multiple( $cache_keys, $group );

	foreach ( $cache as $key => $value ) {
		if ( ! is_array( $value ) ) {
			$cache[ $key ] = false;
			continue;
		}

		if ( ! isset( $value['salt'], $value['data'] ) || $salt !== $value['salt'] ) {
			$cache[ $key ] = false;
			continue;
		}

		$cache[ $key ] = $value['data'];
	}

	return $cache;
}

/**
 * Stores multiple salted values in the cache.
 *
 * @param array        $data   Data to store, keyed by cache key.
 * @param string       $group  The cache group.
 * @param string|array $salt   The timestamp or timestamps indicating when the cache group was last updated.
 * @param int          $expire Optional. When to expire the cache contents, in seconds. Default 0.
 * @return bool[] Array of return values, grouped by key.
 */
function wp_cache_set_multiple_salted( $data, $group, $salt, $expire = 0 ) {
	$salt      = is_array( $salt ) ? implode( ':', $salt ) : $salt;
	$new_cache = array();

	foreach ( $data as $key => $value ) {
		$new_cache[ $key ] = array(
			'data' => $value,
			'salt' => $salt,
		);
	}

	return wp_cache_set_multiple( $new_cache, $group, $expire );
}

/**
 * Determines whether the object cache implementation supports a particular feature.
 *
 * @param string $feature Name of the feature to check for. Possible values include:
 *                        'add_multiple', 'set_multiple', 'get_multiple', 'delete_multiple',
 *                        'flush_runtime', 'flush_group'.
 *
 * @return bool True if the feature is supported, false otherwise.
 */
function wp_cache_supports( $feature ) {
	switch ( $feature ) {
		case 'add_multiple':
		case 'set_multiple':
		case 'get_multiple':
		case 'delete_multiple':
		case 'flush_runtime':
		case 'flush_group':
			return true;

		default:
			return false;
	}
}
