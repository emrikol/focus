	/**
	 * Decrements numeric cache item's value.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key    The cache key to decrement.
	 * @param int        $offset Optional. The amount by which to decrement the item's value. Default 1.
	 * @param string     $group  Optional. The group the key is in. Default 'default'.
	 * @return false|int False on failure, the item's new value on success.
	 */
	public function decr( int|string $key, int $offset = 1, string $group = 'default' ): int|false {
		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group = $this->sanitize_cache_group( $group );
		$key   = $this->key( $key, $group );

		// Key/Group doesn't exist, return false.
		if ( ! $this->isset_internal( $key, $group ) ) {
			return false;
		}

		// Get current expiration BEFORE modifying the value to avoid race conditions.
		$current_expiry = $this->get_expiration( $key, $group );
		if ( $current_expiry < 0 ) {
			// Value has expired, delete it and return false.
			$this->delete( $key, $group );
			return false;
		}

		// Sanitize value.
		$this->cache[ $group ][ $key ] = (int) $this->cache[ $group ][ $key ];

		// Sanitize offset.
		$offset = (int) $offset;

		// Decrement value.
		$this->cache[ $group ][ $key ] -= $offset;

		// Do not let value go negative.
		$this->cache[ $group ][ $key ] = max( 0, $this->cache[ $group ][ $key ] );

		// Save new value to the cache with preserved expiration.
		$this->set( $key, $this->cache[ $group ][ $key ], $group, $current_expiry );

		// Return new value.
		return $this->cache[ $group ][ $key ];
	}

	/**
	 * Removes the contents of the cache key in the group.
	 *
	 * If the cache key does not exist in the group, then nothing will happen.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param int|string $key        What the contents in the cache are called.
	 * @param string     $group      Optional. Where the cache contents are grouped. Default 'default'.
	 * @return bool False if the contents weren't deleted and true on success.
	 */
	public function delete( int|string $key, string $group = 'default' ): bool {
		if ( ! $this->is_valid_key( $key ) ) {
			return false;
		}

		$group  = $this->sanitize_cache_group( $group );
		$key    = $this->key( $key, $group );
		$return = true;

		// Key/Group doesn't exist, return false.
		if ( ! $this->isset_internal( $key, $group ) ) {
			$return = false;
		}

		// Delete cached item and return true.
		unset( $this->cache[ $group ][ $key ] );

		// Delete the cache file.
		if ( $this->focus_file_exists( $key, $group ) ) {
			unlink( $this->get_focus_file( $key, $group ) ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
		}

		// Invalidate expiration cache since we deleted the file.
		$this->invalidate_expiration_cache( $key, $group );

		// Stats.
		$this->group_ops[ $group ][] = 'Delete ' . $key;

		return $return;
	}

	/**
	 * Remove the contents of all cache keys in the group.
	 *
	 * @since 0.1.0
	 * @access public
	 *
	 * @param string|false $group Optional. Where the cache contents are grouped. Default false.
	 * @return bool False if not deleted and true on success.
	 */
	public function delete_group( string|false $group = false ): bool {
		if ( false === $group ) {
			return false;
		}

		if ( ! $this->should_persist( $group ) && ! isset( $this->cache[ $group ] ) ) {
			return false;
		}

		// Delete local cache group.
		unset( $this->cache[ $group ] );

		// Mark all files as expired, just in case delete times out.
		foreach ( glob( $this->cache_dir . $group . '/*.*' ) as $filename ) {
			if ( is_file( $filename ) ) {
				touch( $filename, time() - 3600 ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_touch
			}
		}

		// Delete the cache group dir.
		$this->rm_cache_dir( $this->cache_dir . $group );

		return true;
	}

	/**
	 * Clears the object cache of all data.
