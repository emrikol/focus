	public function is_prefetch_enabled(): bool {
		return WP_FOCUS_CACHE_PREFETCH || $this->test_prefetch_enabled || $this->test_preload_enabled;
	}

	/**
	 * Registers the prefetch manifest save callback for the end of the request.
	 *
	 * @since 1.1.0
	 *
	 * @return void
	 */
	protected function register_prefetch_shutdown_hook(): void {
		if ( $this->prefetch_shutdown_registered ) {
			return;
		}

		$this->prefetch_shutdown_registered = true;

		if ( function_exists( 'add_action' ) ) {
			add_action( 'shutdown', array( $this, 'save_prefetch_manifest' ), PHP_INT_MAX );
			return;
		}

		// @codeCoverageIgnoreStart
		global $wp_filter;

		// phpcs:disable WordPress.WP.GlobalVariablesOverride.Prohibited -- Pre-initialize shutdown hook before add_action() exists.
		if ( ! isset( $wp_filter['shutdown'] ) ) {
			$wp_filter['shutdown'] = array();
		}

		if ( ! isset( $wp_filter['shutdown'][ PHP_INT_MAX ] ) ) {
			$wp_filter['shutdown'][ PHP_INT_MAX ] = array();
		}

		$wp_filter['shutdown'][ PHP_INT_MAX ][] = array(
			'function'      => array( $this, 'save_prefetch_manifest' ),
			'accepted_args' => 0,
		);
		// phpcs:enable WordPress.WP.GlobalVariablesOverride.Prohibited
		// @codeCoverageIgnoreEnd
	}

	/**
	 * Generates the current prefetch manifest cache key.
	 *
	 * @since 1.1.0
	 *
	 * @return string|false Prefetch key, or false when prefetching is disabled.
	 */
	public function get_prefetch_key(): string|false {
		if ( ! $this->is_prefetch_enabled() ) {
			return false;
		}

		$context = $this->get_prefetch_context();
		// @codeCoverageIgnoreStart
		if ( '' === $context ) {
			return false;
		}
		// @codeCoverageIgnoreEnd

		return md5( $context );
	}

