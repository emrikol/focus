class FOCUS_File_Object_Cache extends WP_Object_Cache {}

/**
 * Database-backed FOCUS object cache implementation.
 *
 * @since 1.1.0
 */
class FOCUS_Database_Object_Cache extends WP_Object_Cache {
	/**
	 * Configures the database backend.
	 *
	 * @param string $backend Requested backend.
	 * @return void
	 */
	public function configure_backend( string $backend ): void {
		parent::configure_backend( $backend );

		if ( 'database' !== $this->requested_backend ) {
			return;
		}

		$this->set_database_table_names();
		$this->database_available = '' !== $this->database_buckets_table && '' !== $this->database_items_table && '' !== $this->database_meta_table;

		// @codeCoverageIgnoreStart
		if ( $this->database_available && WP_FOCUS_DATABASE_AUTO_INSTALL ) {
			$this->database_available      = $this->database_schema_current() || $this->install_database_tables();
			$this->database_schema_checked = true;
		}
		// @codeCoverageIgnoreEnd

		if ( $this->database_available ) {
			$this->backend = 'database';
			$this->maybe_run_database_gc();
		}
	}

	/**
	 * Determines whether the active backend is database-backed.
	 *
	 * @return bool Whether the database backend is active.
	 */
	public function is_database_backend(): bool {
		return 'database' === $this->backend && $this->database_available;
	}

	/**
	 * Sets database table names from the WordPress base prefix.
	 *
	 * @return void
	 */
	protected function set_database_table_names(): void {
		global $wpdb;

		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) || empty( $wpdb->base_prefix ) ) {
			return;
		}

		$this->database_buckets_table = $wpdb->base_prefix . 'focus_cache_buckets';
		$this->database_items_table   = $wpdb->base_prefix . 'focus_cache_items';
		$this->database_meta_table    = $wpdb->base_prefix . 'focus_cache_meta';
	}

	/**
	 * Installs database backend tables.
	 *
	 * @return bool Whether the tables exist after install.
	 */
	public function install_database_tables(): bool {
		global $wpdb;

		$this->set_database_table_names();

		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) || '' === $this->database_buckets_table || '' === $this->database_items_table || '' === $this->database_meta_table ) {
			return false;
		}

		$charset = $wpdb->get_charset_collate();
		$buckets = $this->database_buckets_table;
		$items   = $this->database_items_table;
		$meta    = $this->database_meta_table;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.DirectDatabaseQuery.SchemaChange, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$bucket_result = $wpdb->query(
			"CREATE TABLE IF NOT EXISTS `{$buckets}` (
				bucket_hash binary(16) NOT NULL,
				namespace_hash binary(16) NOT NULL,
				scope_type tinyint unsigned NOT NULL,
				network_id bigint unsigned NOT NULL DEFAULT 0,
				blog_id bigint unsigned NOT NULL DEFAULT 0,
				group_hash binary(16) NOT NULL,
				cache_group varchar(191) NOT NULL,
				generation bigint unsigned NOT NULL DEFAULT 1,
				created_at bigint unsigned NOT NULL,
				updated_at bigint unsigned NOT NULL,
				PRIMARY KEY (bucket_hash),
				UNIQUE KEY bucket_identity (namespace_hash, scope_type, network_id, blog_id, group_hash)
			) {$charset}"
		);

		$item_result = $wpdb->query(
			"CREATE TABLE IF NOT EXISTS `{$items}` (
				bucket_hash binary(16) NOT NULL,
				generation bigint unsigned NOT NULL,
				key_hash binary(16) NOT NULL,
				cache_key longtext NOT NULL,
				cache_value longblob NOT NULL,
				value_size int unsigned NOT NULL,
				flags int unsigned NOT NULL DEFAULT 0,
				expires_at bigint unsigned NOT NULL,
				created_at bigint unsigned NOT NULL,
				updated_at bigint unsigned NOT NULL,
				PRIMARY KEY (bucket_hash, generation, key_hash),
				KEY expires_at (expires_at)
			) {$charset}"
		);

		$meta_result = $wpdb->query(
			"CREATE TABLE IF NOT EXISTS `{$meta}` (
				meta_key varchar(191) NOT NULL,
				meta_value longtext NOT NULL,
				updated_at bigint unsigned NOT NULL,
				PRIMARY KEY (meta_key)
			) {$charset}"
		);

		$schema_result = $wpdb->query(
			$wpdb->prepare(
				"INSERT INTO `{$meta}` (meta_key, meta_value, updated_at)
				VALUES (%s, %s, %d)
				ON DUPLICATE KEY UPDATE meta_value = VALUES(meta_value), updated_at = VALUES(updated_at)",
				'schema_version',
				(string) WP_FOCUS_DATABASE_SCHEMA_VERSION,
				time()
			)
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.DirectDatabaseQuery.SchemaChange, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$result = false !== $bucket_result && false !== $item_result && false !== $meta_result && false !== $schema_result;

		$this->database_schema_checked = true;

		if ( $result ) {
			$this->database_available = true;
			if ( 'database' === $this->requested_backend ) {
				$this->backend = 'database';
			}
		}

		return $result;
	}

	/**
	 * Checks whether the installed database schema is current.
	 *
	 * @return bool Whether the installed schema version is current.
	 */
	protected function database_schema_current(): bool {
		global $wpdb;

		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) || '' === $this->database_meta_table ) {
			return false;
		}

		$meta = $this->database_meta_table;

		$suppress_errors = $wpdb->suppress_errors( true );
		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$version = $wpdb->get_var( $wpdb->prepare( "SELECT meta_value FROM `{$meta}` WHERE meta_key = %s LIMIT 1", 'schema_version' ) );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$wpdb->suppress_errors( $suppress_errors );

		return (string) WP_FOCUS_DATABASE_SCHEMA_VERSION === (string) $version;
	}

	/**
	 * Checks whether database backend tables exist.
	 *
	 * @return bool Whether all tables exist.
	 */
	protected function database_tables_exist(): bool {
		global $wpdb;

		foreach ( array( $this->database_buckets_table, $this->database_items_table, $this->database_meta_table ) as $table ) {
			if ( '' === $table ) {
				return false;
			}

			// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
			$columns = $wpdb->get_results( "DESCRIBE `{$table}`" );
			// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
			if ( empty( $columns ) ) {
				return false;
			}
		}

		return true;
	}

	/**
	 * Runs opportunistic database GC.
	 *
	 * @return void
	 */
	protected function maybe_run_database_gc(): void {
		$probability = $this->database_gc_probability;
		if ( $probability > 0 && 1 === mt_rand( 1, $probability ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rand_mt_rand
			$this->run_database_gc();
		}
	}

	/**
	 * Runs bounded database garbage collection.
	 *
	 * @param int $limit Maximum rows per delete class.
	 * @return int Rows deleted.
	 */
	public function run_database_gc( int $limit = 0 ): int {
		global $wpdb;

		if ( ! $this->database_available || ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return 0;
		}

		$limit   = $limit > 0 ? $limit : $this->database_gc_batch_size;
		$items   = $this->database_items_table;
		$buckets = $this->database_buckets_table;
		$now     = time();
		$deleted = 0;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$expired = $wpdb->query( $wpdb->prepare( "DELETE FROM `{$items}` WHERE expires_at <= %d ORDER BY expires_at LIMIT %d", $now, $limit ) );
		$stale   = $wpdb->query( $wpdb->prepare( "DELETE FROM `{$items}` WHERE EXISTS (SELECT 1 FROM `{$buckets}` b WHERE b.bucket_hash = `{$items}`.bucket_hash AND `{$items}`.generation < b.generation) LIMIT %d", $limit ) );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		if ( is_int( $expired ) ) {
			$deleted += $expired;
		}

		if ( is_int( $stale ) ) {
			$deleted += $stale;
		}

		return $deleted;
	}

	/**
	 * Gets a database bucket.
	 *
	 * @param string $group  Cache group.
	 * @param bool   $create Whether to create if missing.
	 * @return array|false Bucket data.
	 */
	protected function get_database_bucket( string $group, bool $create = true ): array|false {
		global $wpdb;

		if ( ! $this->database_available || ! $this->should_persist( $group ) || ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return false;
		}

		$identity  = $this->get_database_bucket_identity( $group );
		$cache_key = implode( ':', array( $identity['bucket_hash'], $identity['scope_type'], $identity['network_id'], $identity['blog_id'], $identity['cache_group'] ) );

		if ( isset( $this->database_buckets[ $cache_key ] ) ) {
			return $this->database_buckets[ $cache_key ];
		}

		$table = $this->database_buckets_table;
		$now   = time();

		if ( $create ) {
			// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
			$wpdb->query(
				$wpdb->prepare(
					"INSERT INTO `{$table}` (bucket_hash, namespace_hash, scope_type, network_id, blog_id, group_hash, cache_group, generation, created_at, updated_at)
					VALUES (UNHEX(%s), UNHEX(%s), %d, %d, %d, UNHEX(%s), %s, 1, %d, %d)
					ON DUPLICATE KEY UPDATE bucket_hash = bucket_hash",
					$identity['bucket_hash'],
					$identity['namespace_hash'],
					$identity['scope_type'],
					$identity['network_id'],
					$identity['blog_id'],
					$identity['group_hash'],
					$identity['cache_group'],
					$now,
					$now
				)
			);
			// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		}

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$generation = $wpdb->get_var( $wpdb->prepare( "SELECT generation FROM `{$table}` WHERE bucket_hash = UNHEX(%s) LIMIT 1", $identity['bucket_hash'] ) );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		if ( null === $generation ) {
			return false;
		}

		$bucket                               = array_merge( $identity, array( 'generation' => (int) $generation ) );
		$this->database_buckets[ $cache_key ] = $bucket;

		return $bucket;
	}

	/**
	 * Builds database bucket identity data.
	 *
	 * @param string $group Cache group.
	 * @return array Bucket identity.
	 */
	protected function get_database_bucket_identity( string $group ): array {
		$group      = $this->sanitize_cache_group( $group );
		$scope_type = empty( $this->global_groups[ $group ] ) ? 3 : 1;

		if ( ! empty( $this->network_groups[ $group ] ) ) {
			$scope_type = 2;
		}

		$network_id = 0;
		$blog_id    = 0;

		if ( 2 === $scope_type ) {
			$network_id = $this->database_network_id;
		} elseif ( 3 === $scope_type ) {
			$network_id = $this->database_network_id;
			$blog_id    = $this->database_blog_id;
		}

		$namespace_hash = md5( $this->key_salt );
		$group_hash     = md5( $group );

		return array(
			'bucket_hash'    => md5( implode( '|', array( $namespace_hash, $scope_type, $network_id, $blog_id, $group_hash ) ) ),
			'namespace_hash' => $namespace_hash,
			'scope_type'     => $scope_type,
			'network_id'     => $network_id,
			'blog_id'        => $blog_id,
			'group_hash'     => $group_hash,
			'cache_group'    => $group,
		);
	}

	/**
	 * Saves a cache item to the database backend.
	 *
	 * @param string $key    Normalized key.
	 * @param mixed  $data   Cache value.
	 * @param string $group  Cache group.
	 * @param int    $expire Expiration in seconds.
	 * @return bool Whether the item was saved.
	 */
	protected function save_to_database( string $key, mixed $data, string $group, int $expire ): bool {
		global $wpdb;

		$bucket = $this->get_database_bucket( $group );
		if ( false === $bucket ) {
			return false;
		}

		$serialized = serialize( $data ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize
		$size       = strlen( $serialized );

		if ( $this->database_max_value_size > 0 && $size > $this->database_max_value_size ) {
			return false;
		}

		$table      = $this->database_items_table;
		$expires_at = time() + $expire;
		$now        = time();

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$result = $wpdb->query(
			$wpdb->prepare(
				"INSERT INTO `{$table}` (bucket_hash, generation, key_hash, cache_key, cache_value, value_size, flags, expires_at, created_at, updated_at)
				VALUES (UNHEX(%s), %d, UNHEX(%s), %s, %s, %d, 0, %d, %d, %d)
				ON DUPLICATE KEY UPDATE cache_key = VALUES(cache_key), cache_value = VALUES(cache_value), value_size = VALUES(value_size), flags = VALUES(flags), expires_at = VALUES(expires_at), updated_at = VALUES(updated_at)",
				$bucket['bucket_hash'],
				$bucket['generation'],
				md5( $key ),
				$key,
				$serialized,
				$size,
				$expires_at,
				$now,
				$now
			)
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$this->expiration_cache[ $group . ':' . $key ] = array(
			'mtime'         => $expires_at,
			'calculated_at' => time(),
		);

		return false !== $result;
	}

	/**
	 * Loads a cache item from the database backend.
	 *
	 * @param string $key   Normalized key.
	 * @param string $group Cache group.
	 * @param bool   $found Found flag.
	 * @return mixed Cache value.
	 */
	protected function load_from_database( string $key, string $group, bool &$found = false ): mixed {
		global $wpdb;

		$found = false;

		if ( ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return false;
		}

		$identity = $this->get_database_bucket_identity( $group );
		$items    = $this->database_items_table;
		$buckets  = $this->database_buckets_table;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$row = $wpdb->get_row( $wpdb->prepare( "SELECT i.cache_value, i.expires_at, i.generation FROM `{$items}` i INNER JOIN `{$buckets}` b ON b.bucket_hash = i.bucket_hash AND b.generation = i.generation WHERE i.bucket_hash = UNHEX(%s) AND i.key_hash = UNHEX(%s) AND i.expires_at > %d LIMIT 1", $identity['bucket_hash'], md5( $key ), time() ), ARRAY_A );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		if ( ! is_array( $row ) ) {
			return false;
		}

		$bucket_cache_key                            = implode( ':', array( $identity['bucket_hash'], $identity['scope_type'], $identity['network_id'], $identity['blog_id'], $identity['cache_group'] ) );
		$this->database_buckets[ $bucket_cache_key ] = array_merge( $identity, array( 'generation' => (int) $row['generation'] ) );

		$value = $this->unserialize_database_value( (string) $row['cache_value'], $key, $group );
		if ( ! $value['found'] ) {
			return false;
		}

		$this->expiration_cache[ $group . ':' . $key ] = array(
			'mtime'         => (int) $row['expires_at'],
			'calculated_at' => time(),
		);

		$found = true;

		return $value['value'];
	}

	/**
	 * Loads multiple cache items from the database backend.
	 *
	 * @param array  $keys  Original keys mapped to normalized keys.
	 * @param string $group Cache group.
	 * @return array Found values keyed by original key.
	 */
	protected function load_multiple_from_database( array $keys, string $group ): array {
		global $wpdb;

		if ( empty( $keys ) || ! isset( $wpdb ) || ! is_object( $wpdb ) ) {
			return array();
		}

		$identity = $this->get_database_bucket_identity( $group );
		$hashes   = array();
		$lookup   = array();
		foreach ( $keys as $original_key => $cache_key ) {
			$hash            = md5( (string) $cache_key );
			$hashes[]        = $hash;
			$lookup[ $hash ] = $original_key;
		}

		$hashes       = array_values( array_unique( $hashes ) );
		$placeholders = implode( ', ', array_fill( 0, count( $hashes ), 'UNHEX(%s)' ) );
		$items        = $this->database_items_table;
		$buckets      = $this->database_buckets_table;
		$values       = array_merge( array( $identity['bucket_hash'] ), $hashes, array( time() ) );

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.ReplacementsWrongNumber
		$rows = $wpdb->get_results( $wpdb->prepare( "SELECT HEX(i.key_hash) AS key_hash, i.cache_key, i.cache_value, i.expires_at, i.generation FROM `{$items}` i INNER JOIN `{$buckets}` b ON b.bucket_hash = i.bucket_hash AND b.generation = i.generation WHERE i.bucket_hash = UNHEX(%s) AND i.key_hash IN ({$placeholders}) AND i.expires_at > %d", $values ), ARRAY_A );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.ReplacementsWrongNumber

		if ( ! is_array( $rows ) ) {
			return array();
		}

		if ( ! empty( $rows ) ) {
			$bucket_cache_key                            = implode( ':', array( $identity['bucket_hash'], $identity['scope_type'], $identity['network_id'], $identity['blog_id'], $identity['cache_group'] ) );
			$this->database_buckets[ $bucket_cache_key ] = array_merge( $identity, array( 'generation' => (int) $rows[0]['generation'] ) );
		}

		$found = array();
		foreach ( $rows as $row ) {
			$hash = strtolower( (string) $row['key_hash'] );
			if ( ! isset( $lookup[ $hash ] ) ) {
				continue;
			}

			$value = $this->unserialize_database_value( (string) $row['cache_value'], (string) $row['cache_key'], $group );
			if ( ! $value['found'] ) {
				continue;
			}

			$found[ $lookup[ $hash ] ] = array(
				'cache_key' => (string) $row['cache_key'],
				'value'     => $value['value'],
			);
		}

		return $found;
	}

	/**
	 * Deletes a cache item from the database backend.
	 *
	 * @param string $key   Normalized key.
	 * @param string $group Cache group.
	 * @return bool Whether an item was deleted.
	 */
	protected function delete_from_database( string $key, string $group ): bool {
		global $wpdb;

		$bucket = $this->get_database_bucket( $group, false );
		if ( false === $bucket ) {
			return false;
		}

		$table = $this->database_items_table;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$deleted = $wpdb->query( $wpdb->prepare( "DELETE FROM `{$table}` WHERE bucket_hash = UNHEX(%s) AND generation = %d AND key_hash = UNHEX(%s)", $bucket['bucket_hash'], $bucket['generation'], md5( $key ) ) );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$this->invalidate_expiration_cache( $key, $group );

		return is_int( $deleted ) && $deleted > 0;
	}

	/**
	 * Flushes all database-backed cache data.
	 *
	 * @return bool Whether tables were flushed.
	 */
	protected function flush_database(): bool {
		global $wpdb;

		$items   = $this->database_items_table;
		$buckets = $this->database_buckets_table;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$items_deleted   = $wpdb->query( "DELETE FROM `{$items}`" );
		$buckets_deleted = $wpdb->query( "DELETE FROM `{$buckets}`" );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$this->database_buckets = array();
		$this->expiration_cache = array();

		return false !== $items_deleted && false !== $buckets_deleted;
	}

	/**
	 * Flushes a database group by bumping bucket generation.
	 *
	 * @param string $group Cache group.
	 * @return bool Whether the group was flushed.
	 */
	protected function flush_database_group( string $group ): bool {
		global $wpdb;

		$bucket = $this->get_database_bucket( $group, false );
		if ( false === $bucket ) {
			return true;
		}

		$table = $this->database_buckets_table;

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$updated = $wpdb->query( $wpdb->prepare( "UPDATE `{$table}` SET generation = generation + 1, updated_at = %d WHERE bucket_hash = UNHEX(%s)", time(), $bucket['bucket_hash'] ) );
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$this->database_buckets = array();
		$this->expiration_cache = array();

		return false !== $updated;
	}

	/**
	 * Loads the saved prefetch manifest through database batch hydration.
	 *
	 * @return void
	 */
	public function load_prefetch_manifest(): void {
		if ( ! $this->is_prefetch_enabled() ) {
			return;
		}

		$prefetch_key = $this->get_prefetch_key();
		if ( false === $prefetch_key ) {
			return;
		}
		$this->record_prefetch_manifest_lookup( $prefetch_key );

		$found    = null;
		$manifest = $this->get( $prefetch_key, $this->prefetch_group, false, $found, false );
		if ( true !== $found || ! is_array( $manifest ) || empty( $manifest['groups'] ) || ! is_array( $manifest['groups'] ) ) {
			return;
		}

		$started = $this->begin_prefetch_manifest_load( $prefetch_key, $manifest );

		try {
			$this->load_prefetch_groups_from_database( $manifest['groups'] );
		} finally {
			$this->finish_prefetch_manifest_load( $started );
		}
	}

	/**
	 * Hydrates prefetch groups from the database backend.
	 *
	 * @param array $groups Grouped manifest keys.
	 * @return void
	 */
	protected function load_prefetch_groups_from_database( array $groups ): void {
		$requests = array();

		foreach ( $groups as $group => $keys ) {
			if ( ! is_string( $group ) || $group === $this->prefetch_group || ! is_array( $keys ) || empty( $keys ) ) {
				continue;
			}

			$keys = $this->sanitize_prefetch_keys( $keys );
			if ( empty( $keys ) ) {
				continue;
			}

			$this->record_prefetch_requested_keys( $group, $keys );

			if ( ! $this->should_persist( $group ) ) {
				continue;
			}

			$bucket = $this->get_database_bucket_identity( $group );

			foreach ( $keys as $key ) {
				$cache_key  = $this->key( $key, $group );
				$key_hash   = md5( $cache_key );
				$lookup_key = $bucket['bucket_hash'] . ':' . $key_hash;

				$requests[ $lookup_key ] = array(
					'group'     => $group,
					'raw_key'   => $key,
					'cache_key' => $cache_key,
					'key_hash'  => $key_hash,
					'bucket'    => $bucket,
				);
			}
		}

		if ( empty( $requests ) ) {
			return;
		}

		foreach ( array_chunk( $requests, max( 1, $this->database_prefetch_chunk_size ), true ) as $chunk ) {
			$this->load_prefetch_request_chunk_from_database( $chunk );
		}
	}

	/**
	 * Hydrates one prefetch request chunk from the database.
	 *
	 * @param array $requests Prefetch request data.
	 * @return void
	 */
	protected function load_prefetch_request_chunk_from_database( array $requests ): void {
		global $wpdb;

		$clauses   = array();
		$values    = array();
		$by_bucket = array();
		$table     = $this->database_items_table;
		$buckets   = $this->database_buckets_table;

		foreach ( $requests as $request ) {
			$bucket_key = $request['bucket']['bucket_hash'];
			if ( ! isset( $by_bucket[ $bucket_key ] ) ) {
				$by_bucket[ $bucket_key ] = array(
					'bucket_hash' => $request['bucket']['bucket_hash'],
					'key_hashes'  => array(),
				);
			}

			$by_bucket[ $bucket_key ]['key_hashes'][] = $request['key_hash'];
		}

		foreach ( $by_bucket as $bucket ) {
			$key_hashes   = array_values( array_unique( $bucket['key_hashes'] ) );
			$placeholders = implode( ', ', array_fill( 0, count( $key_hashes ), 'UNHEX(%s)' ) );

			$clauses[] = "(i.bucket_hash = UNHEX(%s) AND i.key_hash IN ({$placeholders}))";
			$values    = array_merge( $values, array( $bucket['bucket_hash'] ), $key_hashes );
		}

		if ( empty( $clauses ) ) {
			return;
		}

		$started = microtime( true );

		$this->record_prefetch_load_operation();

		$values[] = time();
		$where    = implode( ' OR ', $clauses );

		// phpcs:disable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared
		$rows = $wpdb->get_results(
			$wpdb->prepare(
				"SELECT HEX(i.bucket_hash) AS bucket_hash, i.generation, HEX(i.key_hash) AS key_hash, i.cache_key, i.cache_value, i.expires_at FROM `{$table}` i INNER JOIN `{$buckets}` b ON b.bucket_hash = i.bucket_hash AND b.generation = i.generation WHERE ({$where}) AND i.expires_at > %d",
				$values
			),
			ARRAY_A
		);
		// phpcs:enable WordPress.DB.DirectDatabaseQuery.DirectQuery, WordPress.DB.DirectDatabaseQuery.NoCaching, WordPress.DB.PreparedSQL.InterpolatedNotPrepared

		$elapsed = microtime( true ) - $started;

		if ( ! is_array( $rows ) ) {
			$this->record_database_prefetch_qm_operations( $requests, array(), $started, $elapsed );
			return;
		}

		$loaded_values = array();
		$now           = time();

		foreach ( $rows as $row ) {
			$lookup_key = strtolower( (string) $row['bucket_hash'] ) . ':' . strtolower( (string) $row['key_hash'] );
			if ( ! isset( $requests[ $lookup_key ] ) ) {
				continue;
			}

			$request                                     = $requests[ $lookup_key ];
			$bucket_cache_key                            = implode( ':', array( $request['bucket']['bucket_hash'], $request['bucket']['scope_type'], $request['bucket']['network_id'], $request['bucket']['blog_id'], $request['bucket']['cache_group'] ) );
			$this->database_buckets[ $bucket_cache_key ] = array_merge( $request['bucket'], array( 'generation' => (int) $row['generation'] ) );

			$value = $this->unserialize_database_value( (string) $row['cache_value'], (string) $row['cache_key'], $request['group'] );
			if ( ! $value['found'] ) {
				continue;
			}

			$this->cache[ $request['group'] ][ $request['cache_key'] ]                 = $value['value'];
			$this->expiration_cache[ $request['group'] . ':' . $request['cache_key'] ] = array(
				'mtime'         => (int) $row['expires_at'],
				'calculated_at' => $now,
			);
			$this->record_prefetch_loaded_key( $request['group'], $request['cache_key'] );
			$loaded_values[ $lookup_key ] = $value['value'];
		}

		$this->record_database_prefetch_qm_operations( $requests, $loaded_values, $started, $elapsed );
	}

	/**
	 * Records database prefetch hydration as logical get_multiple operations.
	 *
	 * @since 1.1.0
	 *
	 * @param array $requests      Prefetch request data.
	 * @param array $loaded_values Values hydrated from the database, keyed by lookup key.
	 * @param float $started       Operation start time from microtime( true ).
	 * @param float $elapsed       Measured elapsed time.
	 * @return void
	 */
	protected function record_database_prefetch_qm_operations( array $requests, array $loaded_values, float $started, float $elapsed ): void {
		$groups = array();

		foreach ( $requests as $lookup_key => $request ) {
			$group   = (string) $request['group'];
			$raw_key = isset( $request['raw_key'] ) && ( is_int( $request['raw_key'] ) || is_string( $request['raw_key'] ) ) ? $request['raw_key'] : (string) $request['cache_key'];

			$groups[ $group ]['keys'][ (string) $raw_key ]   = $raw_key;
			$groups[ $group ]['values'][ (string) $raw_key ] = false;

			if ( array_key_exists( $lookup_key, $loaded_values ) ) {
				$groups[ $group ]['values'][ (string) $raw_key ] = $loaded_values[ $lookup_key ];
				$groups[ $group ]['hits'][ (string) $raw_key ]   = true;
			}
		}

		$total_keys = 0;
		foreach ( $groups as $group_data ) {
			$total_keys += count( $group_data['keys'] );
		}

		foreach ( $groups as $group => $group_data ) {
			$keys    = array_values( $group_data['keys'] );
			$hits    = count( $group_data['hits'] ?? array() );
			$misses  = max( 0, count( $keys ) - $hits );
			$time    = $total_keys > 0 ? $elapsed * ( count( $keys ) / $total_keys ) : 0.0;
			$message = sprintf( '%d hits, %d misses', $hits, $misses );

			$this->group_ops[ $group ][] = sprintf( 'get_multiple (%d keys, %d hits, %d misses)', count( $keys ), $hits, $misses );
			$this->record_qm_operation( 'get_multiple', $keys, (string) $group, $group_data['values'], $started, $message, $time );
		}
	}

	/**
	 * Safely unserializes a database value.
	 *
	 * @param string $serialized Serialized value.
	 * @param string $key        Normalized key.
	 * @param string $group      Cache group.
	 * @return array Found/value payload.
	 */
	protected function unserialize_database_value( string $serialized, string $key, string $group ): array {
		if ( '' === $serialized || ! is_serialized( $serialized ) ) {
			$this->delete_from_database( $key, $group );
			return array(
				'found' => false,
				'value' => false,
			);
		}

		$value = unserialize( $serialized ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_unserialize
		// @codeCoverageIgnoreStart
		if ( false === $value && serialize( false ) !== $serialized ) { // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.serialize_serialize
			$this->delete_from_database( $key, $group );
			return array(
				'found' => false,
				'value' => false,
			);
		}
		// @codeCoverageIgnoreEnd

		return array(
			'found' => true,
			'value' => $value,
		);
	}
