	/**
	 * Retrieves multiple values from the cache in one call.
	 *
	 * @since 5.5.0
	 * @access public
	 *
	 * @param array  $keys  Array of keys under which the cache contents are stored.
	 * @param string $group Optional. Where the cache contents are grouped. Default 'default'.
	 * @param bool   $force Optional. Whether to force an update of the local cache
	 *                      from the persistent cache. Default false.
	 * @return array Array of return values, grouped by key. Each value is either
	 *               the cache contents on success, or false on failure.
	 */
	public function get_multiple( $keys, $group = 'default', $force = false ) {
		if ( empty( $keys ) ) {
			return array();
		}

		$group        = $this->sanitize_cache_group( $group );
		$results      = array();
		$missing_keys = array();
		$cache_hits   = 0;
		$cache_misses = 0;
		$start        = microtime( true );

		// First pass: check memory cache for all keys (fast batch operation).
		foreach ( $keys as $key ) {
			if ( ! $this->is_valid_key( $key ) ) {
				$results[ $key ] = false;
				++$cache_misses;
				continue;
			}

			$cache_key = $this->key( $key, $group );

			// Check memory first (unless forced).
			if ( ! $force && $this->isset_internal( $cache_key, $group ) ) {
				$results[ $key ] = $this->cache[ $group ][ $cache_key ];
				$this->record_prefetch_used_key( $group, $cache_key );
				++$cache_hits;
			} else {
				$missing_keys[ $key ] = $cache_key;
			}
		}

		if ( $this->is_database_backend() && ! empty( $missing_keys ) ) {
			$db_values = $this->load_multiple_from_database( $missing_keys, $group );

			foreach ( $missing_keys as $key => $cache_key ) {
				if ( array_key_exists( $key, $db_values ) ) {
					$results[ $key ]                     = $db_values[ $key ]['value'];
					$this->cache[ $group ][ $cache_key ] = $db_values[ $key ]['value'];
					++$cache_hits;
				} else {
					$results[ $key ] = false;
					++$cache_misses;
				}
			}

			$missing_keys = array();
		}

		// Second pass: load missing keys from disk in batch.
		if ( ! empty( $missing_keys ) ) {
			foreach ( $missing_keys as $key => $cache_key ) {
				$disk_value = $this->load_from_disk( $cache_key, $group );
				if ( false !== $disk_value ) {
					$results[ $key ] = $disk_value;
					// Update memory cache for future hits.
					$this->cache[ $group ][ $cache_key ] = $disk_value;
					++$cache_hits;
				} else {
					$results[ $key ] = false;
					++$cache_misses;
				}
			}
		}

		// Update global stats.
		$this->cache_hits   += $cache_hits;
		$this->cache_misses += $cache_misses;

		// Single group stat entry for the batch operation.
		$this->group_ops[ $group ][] = sprintf( 'get_multiple (%d keys, %d hits, %d misses)', count( $keys ), $cache_hits, $cache_misses );
		$this->record_qm_operation( 'get_multiple', array_values( $keys ), $group, $results, $start, sprintf( '%d hits, %d misses', $cache_hits, $cache_misses ) );

		return $results;
	}

	/**
	 * Deletes multiple values from the cache in one call.
	 *
	 * @since 6.0.0
	 * @access public
	 *
	 * @param array  $keys  Array of keys under which the cache to deleted.
	 * @param string $group Optional. Where the cache contents are grouped. Default 'default'.
	 * @return bool[] Array of return values, grouped by key. Each value is either
	 *                true on success, or false if the contents were not deleted.
	 */
	public function delete_multiple( array $keys, $group = 'default' ) {
		if ( empty( $keys ) ) {
			return array();
		}

		$group           = $this->sanitize_cache_group( $group );
		$results         = array();
		$files_to_delete = array();
		$success_count   = 0;
		$start           = microtime( true );

		// First pass: process all keys and collect files to delete.
		foreach ( $keys as $key ) {
			if ( ! $this->is_valid_key( $key ) ) {
				$results[ $key ] = false;
				continue;
			}

			$cache_key = $this->key( $key, $group );

			// Check if key exists in memory or persistent storage.
			$existed_in_memory = $this->isset_internal( $cache_key, $group );
			if ( $this->is_database_backend() ) {
				$deleted_from_storage = $this->delete_from_database( $cache_key, $group );
				$file_path            = '';
				$exists_on_disk       = false;
			} else {
				$file_path            = $this->get_focus_file( $cache_key, $group );
				$exists_on_disk       = $this->focus_file_exists( $cache_key, $group );
				$deleted_from_storage = false;
			}

			// Remove from memory cache.
			unset( $this->cache[ $group ][ $cache_key ] );

			// Determine success (existed in memory OR on disk).
			if ( $existed_in_memory || $exists_on_disk || $deleted_from_storage ) {
				$results[ $key ] = true;
				++$success_count;

				// Collect file for deletion if it exists.
				if ( $exists_on_disk ) {
					$files_to_delete[] = $file_path;
				}
			} else {
				$results[ $key ] = false;
			}
		}

		// Second pass: batch delete files from disk.
		foreach ( $files_to_delete as $file_path ) {
			unlink( $file_path ); // phpcs:ignore WordPress.WP.AlternativeFunctions.unlink_unlink
		}

		// Single group stat entry for the batch operation.
		$this->group_ops[ $group ][] = sprintf( 'delete_multiple (%d keys, %d successful)', count( $keys ), $success_count );
		$this->record_qm_operation( 'delete_multiple', $keys, $group, null, $start, sprintf( '%d successful', $success_count ) );

		return $results;
	}

